/**
 * Builds the BaseLinker SKU index used by the blue "B" badge.
 *
 * Source file: Base__Produkty__*.csv exported from BaseLinker.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { basename, join } from 'node:path';

const root = join(import.meta.dirname, '..');
const input = process.argv[2];

if (!input) {
  throw new Error('Usage: node scripts/build-baselinker-sku-index.mjs <Base__Produkty__.csv>');
}

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let quoted = false;

  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    const next = text[i + 1];

    if (quoted) {
      if (ch === '"' && next === '"') {
        cell += '"';
        i += 1;
      } else if (ch === '"') {
        quoted = false;
      } else {
        cell += ch;
      }
      continue;
    }

    if (ch === '"') {
      quoted = true;
    } else if (ch === ';') {
      row.push(cell);
      cell = '';
    } else if (ch === '\n') {
      row.push(cell.replace(/\r$/, ''));
      rows.push(row);
      row = [];
      cell = '';
    } else {
      cell += ch;
    }
  }

  if (cell || row.length) {
    row.push(cell.replace(/\r$/, ''));
    rows.push(row);
  }

  return rows.filter((r) => r.some((c) => c.trim()));
}

function normalizeSku(raw) {
  const compact = String(raw || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
  const match = compact.match(/^([A-Z]+)0*([0-9]+)$/);
  if (match) return `${match[1]}${Number(match[2])}`;
  return compact;
}

const raw = readFileSync(input, 'utf8').replace(/^\uFEFF/, '');
const rows = parseCsv(raw);
const header = rows.shift()?.map((h) => h.trim()) ?? [];
const skuIdx = header.indexOf('produkt_sku');
const idIdx = header.indexOf('produkt_id');

if (skuIdx < 0 || idIdx < 0) {
  throw new Error(`CSV missing required columns produkt_sku / produkt_id in ${basename(input)}`);
}

const skuToId = {};
for (const row of rows) {
  const sku = String(row[skuIdx] || '').trim().toUpperCase();
  const id = String(row[idIdx] || '').trim();
  if (!sku || !id) continue;

  for (const key of new Set([sku, normalizeSku(sku)])) {
    if (!key) continue;
    skuToId[key] = id;
  }
}

const keys = Object.keys(skuToId).sort((a, b) => a.localeCompare(b, 'pl', { numeric: true }));
const payload = {
  generatedAt: new Date().toISOString(),
  sourceCsv: basename(input),
  skuCount: keys.length,
  skuToId,
};

mkdirSync(join(root, 'public', 'data'), { recursive: true });
writeFileSync(
  join(root, 'public', 'data', 'baselinker-sku-index.json'),
  `${JSON.stringify(payload, null, 2)}\n`,
  'utf8',
);

const lines = [
  '/** Auto-generated by scripts/build-baselinker-sku-index.mjs - do not edit */',
  `// Source: ${basename(input)} - ${rows.length} rows - ${keys.length} SKU keys`,
  '',
  'export const BASELINKER_SKU_TO_ID: Record<string, string> = {',
];

for (const key of keys) {
  lines.push(`  ${JSON.stringify(key)}: ${JSON.stringify(skuToId[key])},`);
}
lines.push('};');
lines.push('');
lines.push('export const BASELINKER_SKUS = new Set<string>(Object.keys(BASELINKER_SKU_TO_ID));');
lines.push('');

writeFileSync(join(root, 'src', 'lib', 'baselinkerSkuIndex.generated.ts'), `${lines.join('\n')}\n`, 'utf8');

console.log(`OK: ${rows.length} rows -> ${keys.length} BaseLinker SKU keys`);
console.log('  src/lib/baselinkerSkuIndex.generated.ts');
console.log('  public/data/baselinker-sku-index.json');
